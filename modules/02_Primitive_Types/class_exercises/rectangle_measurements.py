widthOfRectangle = input("enter the width of a rectangle: ")
W = float(widthOfRectangle)
heightOfRectangle = input("enter the height of a rectangle:")
H = float(heightOfRectangle)

areaOfTheRectangle = W * H
perimeterOfTheRectangle = 2 * (W + H)
diagonalOfTheRectangle = (W ** 2 + H ** 2) ** 0.5

print("Width:", W )
print("Height:", H )
print("Area:", areaOfTheRectangle )
print("Perimeter:", perimeterOfTheRectangle )
print("diagonal:", diagonalOfTheRectangle )



