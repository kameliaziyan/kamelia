temperature = input("Enter temperature in Celsius: ")
convertToFloat = float(temperature)
convertToFahrenheit = ( convertToFloat * 9/5 ) + 32
convertToKelvin = convertToFloat + 273.15


print("Temperature in Celsius:", convertToFloat)
print("Temperature in Fahrenheit:", convertToFahrenheit)
print("Temperature in Kelvin:", convertToKelvin)


